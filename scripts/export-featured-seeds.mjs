#!/usr/bin/env node
// Export the best seeds of the seed-search runs for the static seed page.
//
//   node scripts/export-featured-seeds.mjs [--count 100]
//       top seeds per mod config from the explorer database
//       (space_explorer_gui/data.sqlite), for configs it holds a real run of
//   node scripts/export-featured-seeds.mjs --scan se [--range 0:50000000] [--workers 10] [--count 100]
//       search a config directly with seedgen instead - nothing is written to
//       the database or output/; only seeds with at least --min-planets
//       (default 12) Calidus planets are kept, which is what the score ranks
//       first
//
// Writes space_explorer_gui/public/featured-seeds.json. Configs that are not
// regenerated by a run keep their existing entry. The static site has no
// database, so this small file is how it can still suggest seeds.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import readline from "node:readline";
import { spawn } from "node:child_process";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const GUI = path.join(ROOT, "space_explorer_gui");
const OUT = path.join(GUI, "public", "featured-seeds.json");
const require = createRequire(path.join(GUI, "package.json"));
const { seedScore } = require(path.join(GUI, "score.js"));

const arg = (name, fallback) => {
  const i = process.argv.indexOf(name);
  return i !== -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
};
const COUNT = parseInt(arg("--count", "100"), 10);
const K2 = { k2se: 1, se: 0 };
// only a real run is worth featuring, not a handful of seeds opened by hand
const MIN_SEARCHED = 1000;

const entry = (r) => ({
  seed: r.seed,
  score: r.score,
  planets: r.npl,          // Calidus planets, incl. Nauvis
  bodies: r.npm,           // Calidus planets + moons
  loot: r.loot,
  naquiumDv: r.naqdv,      // Δv to the nearest naquium-primary field
  fieldDv: r.fdv,          // Δv to the nearest asteroid field of any kind
  hostile: r.ef,           // % of bodies with enemies
  water: r.wp,             // % of bodies with water
});
const byScore = (a, b) => b.score - a.score || a.seed - b.seed;

function fromDatabase() {
  const Database = require("better-sqlite3");
  const db = new Database(path.join(GUI, "data.sqlite"), { readonly: true });
  const configs = {};
  for (const [mod, k2] of Object.entries(K2)) {
    const searched = db.prepare("SELECT COUNT(*) AS n FROM seeds WHERE k2 = ?").get(k2).n;
    if (searched < MIN_SEARCHED) continue;
    const range = db.prepare("SELECT MIN(seed_start) AS lo, MAX(seed_end) AS hi FROM universe_jobs WHERE k2_enabled = ? AND status = 'done'").get(k2);
    const rows = db.prepare(
      `SELECT seed, score, loot, npl, npm, naqdv, fdv, ef, wp FROM seeds
       WHERE k2 = ? AND score IS NOT NULL ORDER BY score DESC, seed ASC LIMIT ?`).all(k2, COUNT);
    configs[mod] = { searched: range.hi != null ? range.hi - range.lo : searched, seeds: rows.map(entry) };
  }
  return configs;
}

// Run seedgen over [lo, hi) split across workers; keep the scored survivors.
async function scan(mod, lo, hi, workers, minPlanets) {
  const bin = path.join(ROOT, "universe_generator", "zig", process.platform === "win32" ? "seedgen.exe" : "seedgen");
  if (!fs.existsSync(bin)) throw new Error("seedgen not built (run node install.mjs)");
  const filter = JSON.stringify({ $count: {
    of: { "&&": [{ starSystem: { "==": "Calidus" } }, { type: { "==": "planet" } }] },
    is: { ">=": minPlanets },
  } });
  const span = Math.ceil((hi - lo) / workers);
  const found = [];
  const progress = new Array(workers).fill(0);
  const t0 = Date.now();
  let lastReport = 0;
  await Promise.all(Array.from({ length: workers }, (_, w) => new Promise((resolve, reject) => {
    const a = lo + w * span, b = Math.min(hi, a + span);
    if (a >= b) return resolve();
    const child = spawn(bin, [], {
      env: { ...process.env, START_SEED: String(a), END_SEED: String(b), SE_K2: String(K2[mod]), FILTER: filter, MIN_PROD_MODULES: "0", WORKER_ID: String(w) },
      stdio: ["ignore", "pipe", "pipe"],
    });
    readline.createInterface({ input: child.stdout }).on("line", (line) => {
      if (!line.startsWith("{")) return;
      const d = JSON.parse(line);
      const r = { seed: d.s, loot: d.l, npl: d.npl, npm: d.npm, naqdv: d.naqdv, fdv: d.fdv, ef: d.ef, wp: d.wp };
      r.score = seedScore(r);
      if (r.score != null) found.push(r);
    });
    child.stderr.on("data", (buf) => {
      const m = /seed\s+(\d+)/.exec(buf.toString().split("\n").filter(Boolean).pop() || "");
      if (m) progress[w] = parseInt(m[1], 10) - a;
      if (Date.now() - lastReport > 60000) {
        lastReport = Date.now();
        const done = progress.reduce((x, y) => x + y, 0);
        console.log(`  ${mod}: ${(100 * done / (hi - lo)).toFixed(0)}% of ${(hi - lo).toLocaleString()} seeds, ${found.length} kept, ${Math.round((Date.now() - t0) / 60000)} min`);
      }
    });
    child.on("error", reject);
    child.on("close", (code) => (code === 0 ? resolve() : reject(new Error(`seedgen worker ${w} exited ${code}`))));
  })));
  found.sort(byScore);
  return { searched: hi - lo, seeds: found.slice(0, COUNT).map(entry) };
}

const existing = fs.existsSync(OUT) ? JSON.parse(fs.readFileSync(OUT, "utf8")).configs || {} : {};
const scanMod = arg("--scan", null);
let fresh;
if (scanMod) {
  if (!(scanMod in K2)) throw new Error(`--scan must be one of ${Object.keys(K2).join(", ")}`);
  const [lo, hi] = arg("--range", "0:50000000").split(":").map(Number);
  const workers = parseInt(arg("--workers", String(Math.max(1, os.cpus().length))), 10);
  console.log(`scanning ${scanMod} seeds ${lo.toLocaleString()}..${hi.toLocaleString()} on ${workers} workers`);
  fresh = { [scanMod]: await scan(scanMod, lo, hi, workers, parseInt(arg("--min-planets", "12"), 10)) };
} else {
  fresh = fromDatabase();
}
const configs = { ...existing, ...fresh };
fs.writeFileSync(OUT, JSON.stringify({ configs }, null, 1) + "\n");
for (const [mod, c] of Object.entries(fresh)) {
  const s = c.seeds;
  console.log(`${mod}: top ${s.length} of ${c.searched.toLocaleString()} searched seeds` + (s.length ? ` (scores ${s[0].score}..${s[s.length - 1].score})` : ""));
}
console.log("wrote " + path.relative(ROOT, OUT));
