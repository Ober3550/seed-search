// Emit space_explorer_gui/public/ab-table.js from surface_generator/biome/
// biomes-table.json so the GPU worker can pack the alien-biomes classifier
// rows (156) + per-row tv_seeds without loading the GUI mod data dir.
// Usage: node scripts/emit-biomes-table.mjs
import { readFileSync, writeFileSync } from "node:fs";

const rows = JSON.parse(readFileSync("surface_generator/biome/biomes-table.json", "utf8"));
const out = `// GENERATED by scripts/emit-biomes-table.mjs — alien-biomes classifier rows.
// Keep in sync with surface_generator/biome/biomes-table.json (biome_table.zig).
const AB_BIOMES = ${JSON.stringify(rows.map((r) => ({
  t: r.t, m: r.m, a: r.a, e: r.e,
  crater: !!r.crater, beach: r.beach_weight, wc: r.water_coef,
  tv: r.tv_seed, c: r.color,
}))).replaceAll("},", "},\n")};
const AB_WATER_SEED = 4214428890; // crc32("water")  (biome.zig)
const AB_CRATER_SEED = 3394482400; // crc32("crater")
`;
writeFileSync("space_explorer_gui/public/ab-table.js", out);
console.log("wrote", "space_explorer_gui/public/ab-table.js", rows.length, "rows");
