// Regenerate surface_generator/src/sa_embedded.zig from the extracted SA data.
// Zig's @embedFile is restricted to the module's package tree, so the JSON
// files (which live outside src/) are inlined here as multiline string
// literals instead. Re-run after re-extracting sa-data:
//
//   node scripts/gen-sa-embed.mjs
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const SURF = path.join(ROOT, "surface_generator", "sa-data", "surfaces");
const OUT = path.join(ROOT, "surface_generator", "src", "sa_embedded.zig");

const names = ["vulcanus", "fulgora", "gleba", "aquilo", "nauvis"];
const EXTRA = [["planets", path.join(ROOT, "surface_generator", "sa-data", "planets.json")]];

function zigMulti(s) {
  // Zig multiline literal: lines prefixed with '\'; content is literal
  // (JSON from the extractor contains no backslashes or embedded quotes).
  const lines = s.split("\n");
  return lines.map((l) => "    \\\\" + l).join("\n");
}

let out = "// Auto-generated by scripts/gen-sa-embed.mjs — do not edit.\n";
out += "// Inline copies of surface_generator/sa-data/surfaces/*.json so the Zig\n";
out += "// build stays self-contained (see sa_data.zig).\n\n";
for (const n of names) {
  const p = path.join(SURF, `${n}.json`);
  const txt = fs.readFileSync(p, "utf8").replace(/\n$/, "");
  out += `pub const ${n} =\n${zigMulti(txt)}\n;\n\n`;
}
for (const [n, p] of EXTRA) {
  const txt = fs.readFileSync(p, "utf8").replace(/\n$/, "");
  out += `pub const ${n} =\n${zigMulti(txt)}\n;\n\n`;
}
fs.writeFileSync(OUT, out);
console.log(`wrote ${OUT} (${names.length} surfaces)`);
